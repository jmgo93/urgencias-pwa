import { TonalPalette, hexFromArgb } from '@material/material-color-utilities';
import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SECTION_THEMES, FALLBACK_SECTION_THEME } from '../src/section-themes.js';

const roles = {
  light: { accent: 40, container: 90, 'on-container': 10 },
  dark: { accent: 80, container: 30, 'on-container': 90 },
};

function themeRule(theme, mode) {
  const palette = TonalPalette.fromHueAndChroma(theme.hue, theme.chroma);
  const selector = theme.id === 'other' ? ':root, [data-section-theme="other"]' : `[data-section-theme="${theme.id}"]`;
  const tokens = Object.entries(roles[mode]).map(([role, tone]) => `  --section-${role}: ${hexFromArgb(palette.tone(tone))};`).join('\n');
  return `${selector} {\n${tokens}\n}`;
}

export function renderSectionTokens() {
  const themes = [FALLBACK_SECTION_THEME, ...SECTION_THEMES];
  const light = themes.map(theme => themeRule(theme, 'light')).join('\n');
  const dark = themes.map(theme => themeRule(theme, 'dark')).join('\n');
  return `/* Generated by scripts/generate-section-tokens.mjs using Material HCT tonal palettes.\n   Section identity supplements its icon and name; it is not a clinical severity scale. */\n${light}\n@media (prefers-color-scheme: dark) {\n${dark}\n}\n`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await writeFile(new URL('../src/section-tokens.css', import.meta.url), renderSectionTokens());
  console.log('Identidad de 25 secciones preparada para temas claro y oscuro.');
}
